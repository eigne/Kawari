test("bolt starts and expires movement effect",function()
    local m=fresh();m.command(1,"bolt",0,0);assert(m.actors[1].statuses.bolt)
    m.advance(10);assert(not m.actors[1].statuses.bolt)
    local events=m.drain();local n=0;for _,e in ipairs(events) do if e.kind=="speed" then n=n+1 end end;eq(n,2)
