-- Behavioral tests run by cargo test -p kawari-world feast.
local function eq(a,b,label) assert(a==b,(label or "value")..": "..tostring(a).." ~= "..tostring(b)) end
local function fresh()
    local m=make_engine()
    m.sync({
        {id=1,hp=10000,max_hp=20000,mp=10000,x=0,y=0,z=0,player=true,job=24},
        {id=2,hp=1000,max_hp=20000,mp=10000,x=2,y=0,z=0,player=true,job=24},
        {id=3,hp=20000,max_hp=20000,mp=10000,x=3,y=0,z=0,player=false,job=0},
        {id=4,hp=20000,max_hp=20000,mp=10000,x=4,y=0,z=0,player=true,job=24},
        {id=5,hp=1000,max_hp=20000,mp=10000,x=40,y=0,z=0,player=true,job=24},
    },0)
    for _,id in ipairs({1,2,4,5}) do m.command(id,"on",0,0) end
    m.command(4,"team claw",0,0)
    return m
end
local count=0
local function test(name,fn) fn();count=count+1 end
test("all 20 historical action IDs are distinct",function()
    local m=fresh();local n=0;local ids={}
    for _,d in pairs(m.actions) do assert(not ids[d.id]);ids[d.id]=true;n=n+1 end
    eq(n,20)
end)
for _,case in ipairs({{"cure",2000,0,1.5},{"cure2",4000,1000,1.5},{"tetra",4000,0,0}}) do
    test(case[1],function()
        local m=fresh();m.command(1,case[1],2,0);m.advance(case[4])
        eq(m.actors[2].hp,1000+case[2]);eq(m.actors[1].mp,10000-case[3])
    end)
end
test("medica heals nearby teammates only",function()
    local m=fresh();m.command(1,"medica",3,0);m.advance(2)
    eq(m.actors[1].hp,12000);eq(m.actors[2].hp,3000);eq(m.actors[5].hp,1000)
    eq(m.actors[3].hp,20000);eq(m.actors[4].hp,20000);eq(m.actors[1].mp,9000)
end)
test("glare fixed Feast potency",function()
    local m=fresh();m.command(1,"glare",3,0);m.advance(1.5);eq(m.actors[3].hp,18800)
end)
test("dia debuff increases subsequent hits and expires",function()
    local m=fresh();m.command(1,"dia",3,0);eq(m.actors[3].hp,19200)
    eq(m.modify_damage(1,3,1000,1),1100);eq(m.modify_damage(1,3,1000,15),1000)
    m.advance(15);eq(m.actors[3].hp,19200,"Dia is not a DoT")
end)
test("solace costs lily, nourishes blood, five regen ticks",function()
    local m=fresh();m.players[1].lilies=1;m.players[1].blood=2
    m.command(1,"solace",2,0);eq(m.actors[2].hp,5000);eq(m.players[1].lilies,0);eq(m.players[1].blood,3)
    m.advance(15);eq(m.actors[2].hp,7000);m.advance(30);eq(m.actors[2].hp,7000)
end)
