        {id=5,hp=1000,max_hp=20000,mp=10000,x=40,y=0,z=0,player=true,job=24},
    },0)
    for _,id in ipairs({1,2,4,5}) do m.command(id,"on",0,0) end
    m.command(4,"team claw",0,0)
    return m
end
