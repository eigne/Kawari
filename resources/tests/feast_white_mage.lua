test("purify works while afflicted and doubles on cleanse",function()
    local m=fresh();m.actors[1].statuses.sleep={expires=3};m.actors[2].statuses.bind={expires=3}
    m.command(1,"purify",2,0);eq(m.actors[2].hp,5000);assert(not m.actors[2].statuses.bind)
    local n=fresh();n.command(1,"purify",2,0);eq(n.actors[2].hp,3000)
    local p=fresh();p.actors[2].native_statuses={2};p.command(1,"purify",2,0);eq(p.actors[2].hp,5000)
